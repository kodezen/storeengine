export const getSubscriptionInitialValues = ( ID = null, data = {} ) => {
	const schema = {
		status: 'auto-draft',
		currency: '',
		is_editable: false,
		type: '',
		tax_amount: 0,
		total_discount: 0,
		customer_name: '',
		customer_email: '',
		total_amount: '',
		customer_id: 0,
		billing_email: '',
		parent_order_id: '',
		payment_method: '',
		payment_method_title: '',
		transaction_id: '',
		ip_address: '',
		user_agent: '',
		customer_note: '',
		payment_duration: 0,
		payment_duration_type: '',
		hash: '',
		refunds_total: 0,
		subtotal_amount: 0,
		meta: {},
		refunds: [],
		notes: [],
		taxes: [],
		fees: [],
		coupons: [],
		related_orders: [],
		purchase_items: [],
		billing_address: '',
		shipping_address: '',
		billing_periods: '',
	};

	if ( ID && data && data.length ) {
		data = data.filter(
			( item ) => parseInt( item.id ) === parseInt( ID )
		);
		const {
			id,
			status,
			is_editable,
			coupons,
			currency,
			type,
			tax_amount,
			total_amount,
			total_discount,
			customer_id,
			customer_name,
			customer_email,
			billing_email,
			parent_order_id,
			payment_method,
			payment_method_title,
			transaction_id,
			ip_address,
			user_agent,
			customer_note,
			refunds,
			refunds_total,
			subtotal_amount,
			hash,
			notes,
			taxes,
			fees,
			meta,
			purchase_items,
			billing_address,
			shipping_address,
			related_orders,
			end_date,
			next_payment_date,
			trial_end_date,
			start_date,
			payment_duration,
			payment_duration_type,
		} = data[ 0 ];

		return {
			id,
			currency,
			status,
			is_editable,
			type,
			tax_amount,
			total_amount,
			customer_name,
			customer_email,
			customer_id,
			billing_email,
			parent_order_id,
			payment_method,
			payment_method_title,
			transaction_id,
			ip_address,
			user_agent,
			customer_note,
			total_discount,
			subtotal_amount,
			hash,
			notes: notes || [],
			taxes: taxes || [],
			fees: fees || [],
			coupons: coupons || [],
			end_date,
			next_payment_date,
			trial_end_date,
			start_date,
			payment_duration,
			payment_duration_type,
			meta: {
				stripe_payment_intent_id: meta?.stripe_payment_intent_id,
				next_payment_date: meta?.next_payment_date,
				stripe_customer_id: meta?.stripe_customer_id,
				stripe_payment_method_id: meta?.stripe_payment_method_id,
				last_payment_date: meta?.last_payment_date,
			},
			purchase_items,
			refunds,
			refunds_total,
			related_orders,
			billing_address,
			shipping_address,
		};
	}
	return schema;
};
